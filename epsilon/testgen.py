def _js_file(spec_name: str, target: str, cases: list, setup: str,
             lang: str) -> str:
    L: list[str] = []
    L.append('// Generated by epsilon testgen from TestSpec %r.' % spec_name)
    if lang == 'typescript':
        L.append('// Run with a TypeScript-aware runner (tsc/ts-node).')
    L.append("const { test } = require('node:test');")
    L.append("const assert = require('node:assert/strict');")
    L.append('')
    L.append('const TARGET_PATH = %s;' % json.dumps(target))
    L.append('const _parts = TARGET_PATH.split(".");')
    L.append('const _attr = _parts.length > 1 ? _parts.pop() : null;')
    if lang == 'typescript':
        L.append("const _mod = require('../' + _parts.join('/'));")
    else:
        L.append("const _mod = require('../' + _parts.join('/') + '.js');")
    L.append('const TARGET = _attr ? _mod[_attr] : _mod;')
    L.append('')
    if setup and str(setup).strip():
        for line in str(setup).splitlines():
            L.append(line.rstrip())
        L.append('')
    if not cases:
        L.append('// spec holds no cases; add TestCase nodes to cover it')
    for i, case in enumerate(cases):
        given = _get(case, 'given', None)
        expect = _get(case, 'expect', '')
        raises = _get(case, 'raises', None)
        note = _one_line_note(_get(case, 'note', ''))
        title = 'case %d' % i + (': ' + note if note else '')
        title = title.replace('\\', '\\\\').replace("'", "\\'")
        L.append("test('%s', () => {" % title)
        args = _js_args(given)
        if args is None:
            L.append('  // unrepresentable given value; manual review needed')
            L.append('});')
            continue
        if raises:
            exc = _exc_name(raises) or 'Error'
            L.append('  assert.throws(() => { TARGET%s; }, /%s/);'
                     % (args, re.escape(exc)))
            L.append('});')
            continue
        L.append('  const actual = TARGET%s;' % args)
        for line in _js_expect_block(expect):
            L.append('  ' + line)
        L.append('});')
    return '\n'.join(L) + '\n'


def tests_for(project) -> dict:
    """Render one real test file per TestSpec. Returns {path: content}.

    Path convention: tests/test_<slug>.py for Python,
    tests/<slug>.test.js / tests/<slug>.test.ts for JavaScript/TypeScript,
    where <slug> derives from the spec name (or target). Specs with an empty
    target are skipped: without a target there is nothing to resolve.
    """
    lang = _proj_lang(project)
    out: dict[str, str] = {}
    used: set[str] = set()
    for i, spec in enumerate(_specs(project)):
        name = _get(spec, 'name', '') or ''
        target = (_get(spec, 'target', '') or '').strip()
        if not target:
            continue
        slug = _slug(name or target, 'spec_%d' % i)
        if lang == 'python':
            path = 'tests/test_%s.py' % slug
        elif lang == 'typescript':
            path = 'tests/%s.test.ts' % slug
        else:
            path = 'tests/%s.test.js' % slug
        n = 2
        while path in used:
            if lang == 'python':
                path = 'tests/test_%s_%d.py' % (slug, n)
            elif lang == 'typescript':
                path = 'tests/%s_%d.test.ts' % (slug, n)
            else:
                path = 'tests/%s_%d.test.js' % (slug, n)
            n += 1
        used.add(path)
        cases = _cases(spec)
        setup = _get(spec, 'setup', '') or ''
        if lang == 'python':
            out[path] = _python_file(name or target, target, cases, setup)
        else:
            out[path] = _js_file(name or target, target, cases, setup, lang)
    return out


def regression_test(target, given, expect, style='value'):
    """Build a one-case TestSpec from a discovered failure. None if unusable.

    style selects the case shape: 'value' (default) treats expect as a Python
    value and stores its repr() as the expected literal; 'literal' stores an
    expect string verbatim as the expected literal; 'raises' treats expect as
    an exception name for an assertRaises-style case. Unknown styles, empty
    targets, and non-literal-representable values yield None.
    """
    if not isinstance(target, str) or not target.strip():
        return None
    target = target.strip()
    norm = style.lower() if isinstance(style, str) else ''
    name = 'regression_' + _slug(target, 'case')
    if norm == 'raises':
        if isinstance(expect, str) and _exc_name(expect):
            exc = _exc_name(expect)
        elif isinstance(expect, type) and issubclass(expect, BaseException):
            exc = expect.__name__
        elif isinstance(expect, BaseException):
            exc = type(expect).__name__
        else:
            return None
        case = TestCase(given=given, expect='',
                        raises=exc, note='regression: %s raised %s' % (target, exc))
        return TestSpec(name=name, target=target, cases=[case], setup='')
    if norm in ('literal', 'source', 'expect-literal'):
        if not isinstance(expect, str):
            return None
        case = TestCase(given=given, expect=expect,
                        note='regression: %s' % target)
        return TestSpec(name=name, target=target, cases=[case], setup='')
    if norm in ('', 'value'):
        try:
            literal = repr(expect)
        except Exception:
            return None
        try:
            ast.literal_eval(literal)
        except Exception:
            return None
        case = TestCase(given=given, expect=literal,
                        note='regression: %s' % target)
        return TestSpec(name=name, target=target, cases=[case], setup='')
    return None
