"""Epsilon v2 test generator. Real tests from HIR TestSpecs, stdlib only.

tests_for() renders one test file per TestSpec: unittest.TestCase files for
Python, node:test files for JavaScript/TypeScript. Every case in the spec --
including edge, invalid, and integration cases -- becomes an assertion block.
Nothing is invented: a spec with N cases yields exactly N test methods.

Calling convention per case (from TestCase.given):
  tuple/list -> positional args, dict -> keyword args (Python) or a single
  object argument (JS, which has no kwargs), any other value -> one argument.
TestCase.expect is a source literal; the generator validates it with
ast.literal_eval at render time and falls back to embedding it verbatim
(with a comment) when it is not a plain literal. TestCase.raises selects
assertRaises / assert.throws instead of a value comparison.
"""
from __future__ import annotations

import ast
import json
import re

from .hir import TestCase, TestSpec


def _get(obj, key: str, default=None):
    if isinstance(obj, dict):
        return obj.get(key, default)
    return getattr(obj, key, default)


def _slug(text: str, fallback: str) -> str:
    s = re.sub(r'[^0-9a-z]+', '_', (text or '').lower()).strip('_')
    return s or fallback


def _proj_lang(project) -> str:
    lang = (_get(project, 'language', 'python') or 'python').lower()
    if lang == 'js':
        return 'javascript'
    if lang not in ('python', 'javascript', 'typescript'):
        return 'python'
    return lang


def _specs(project) -> list:
    return list(_get(project, 'tests', []) or [])


def _cases(spec) -> list:
    return list(_get(spec, 'cases', []) or [])


def _safe_repr(value):
    try:
        return repr(value)
    except Exception:
        return None


def _call_expr(given):
    """Render the argument list for a TARGET(...) call. None if unrenderable."""
    if given is None:
        return '()'
    if isinstance(given, dict):
        parts = []
        for k in sorted(given.keys(), key=str):
            r = _safe_repr(given[k])
            if r is None:
                return None
            parts.append('%s=%s' % (k, r))
        return '(%s)' % ', '.join(parts)
    if isinstance(given, (list, tuple)):
        parts = []
        for v in given:
            r = _safe_repr(v)
            if r is None:
                return None
            parts.append(r)
        return '(%s)' % ', '.join(parts)
    r = _safe_repr(given)
    if r is None:
        return None
    return '(%s)' % r


def _method_name(i: int, note: str) -> str:
    base = 'test_%02d' % i
    if note:
        base += '_' + _slug(note, 'case')[:24]
    return base


def _one_line_note(note) -> str:
    return ' '.join(str(note or '').split())


def _class_name(spec_name: str, target: str) -> str:
    slug = _slug(spec_name or target, 'generated')
    camel = ''.join(p[:1].upper() + p[1:] for p in slug.split('_'))
    name = 'Test' + (camel or 'Generated')
    if not re.match(r'^[A-Za-z_][A-Za-z0-9_]*$', name):
        return 'TestGenerated'
    return name


def _exc_name(raises) -> str:
    name = str(raises or '').strip()
    if re.match(r'^[A-Za-z_][A-Za-z0-9_.]*$', name):
        return name
    return ''


def _python_file(spec_name: str, target: str, cases: list, setup: str) -> str:
    L: list[str] = []
    L.append('"""Generated by epsilon testgen from TestSpec %r."""' % spec_name)
    L.append('import importlib')
    L.append('import unittest')
    L.append('')
    L.append('TARGET_PATH = %r' % target)
    L.append('def _resolve(dotted):')
    L.append('    mod, sep, attr = dotted.rpartition(".")')
    L.append('    if sep:')
    L.append('        try:')
    L.append('            m = importlib.import_module(mod)')
    L.append('        except ImportError:')
    L.append('            return importlib.import_module(dotted)')
    L.append('        obj = m')
    L.append('        for part in attr.split("."):')
    L.append('            obj = getattr(obj, part)')
    L.append('        return obj')
    L.append('    return importlib.import_module(dotted)')
    L.append('')
    L.append('TARGET = _resolve(TARGET_PATH)')
    L.append('')
    if setup and str(setup).strip():
        for line in str(setup).splitlines():
            L.append(line.rstrip())
        L.append('')
    L.append('class %s(unittest.TestCase):' % _class_name(spec_name, target))
    if not cases:
        L.append('    pass  # spec holds no cases; add TestCase nodes to cover it')
    for i, case in enumerate(cases):
        given = _get(case, 'given', None)
        expect = _get(case, 'expect', '')
        raises = _get(case, 'raises', None)
        note = _one_line_note(_get(case, 'note', ''))
        L.append('    def %s(self):' % _method_name(i, note))
        if note:
            L.append('        # %s' % note)
        args = _call_expr(given)
        if args is None:
            L.append('        self.skipTest("unrepresentable given value")')
            continue
        if raises:
            exc = _exc_name(raises)
            if not exc:
                exc = 'Exception  # original raises=%r not an identifier' % (raises,)
            L.append('        with self.assertRaises(%s):' % exc)
            L.append('            TARGET%s' % args)
            continue
        try:
            ast.literal_eval(expect)
            literal_ok = True
        except Exception:
            literal_ok = False
        if not literal_ok:
            L.append('        # non-literal expect from spec; compared verbatim')
        L.append('        actual = TARGET%s' % args)
        L.append('        expected = %s' % expect)
        L.append('        self.assertEqual(actual, expected)')
    L.append('')
    L.append("if __name__ == '__main__':")
    L.append('    unittest.main()')
    return '\n'.join(L) + '\n'


def _js_value(value):
    if isinstance(value, tuple):
        value = list(value)
    if isinstance(value, set):
        value = sorted(value, key=repr)
    try:
        return json.dumps(value, sort_keys=True)
    except (TypeError, ValueError):
        return None


def _js_args(given):
    if given is None:
        return '()'
    if isinstance(given, dict):
        v = _js_value(given)
        return None if v is None else '(%s)' % v
    if isinstance(given, (list, tuple)):
        parts = []
        for item in given:
            v = _js_value(item)
            if v is None:
                return None
            parts.append(v)
        return '(%s)' % ', '.join(parts)
    v = _js_value(given)
    return None if v is None else '(%s)' % v


def _js_expect_block(expect) -> list[str]:
    """Assertion lines over an already-bound `actual` value."""
    try:
        py_value = ast.literal_eval(expect)
    except Exception:
        literal_ok = False
    else:
        literal_ok = True
    if literal_ok:
        js_lit = _js_value(py_value)
        if js_lit is None:
            literal_ok = False
    if not literal_ok:
        return ['// non-literal expect from spec; compared as an expression',
                'assert.strictEqual(actual, (%s));' % expect]
    return ['assert.strictEqual(actual, %s);' % js_lit]
